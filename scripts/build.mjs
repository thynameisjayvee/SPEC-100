import { stripTypeScriptTypes } from 'node:module';
import { mkdir, readFile, writeFile, cp } from 'node:fs/promises';
const portable = 'skills/spec100-setup';
const templates = `${portable}/assets/templates`;
await mkdir(`${portable}/scripts`, { recursive: true });
await mkdir('plugins/spec100/runtime', { recursive: true });
const source = (await readFile('src/runtime.cts', 'utf8')).replace(/\r\n/g, '\n');
const runtime = '// Generated by npm run build. Source: src/runtime.cts.\n' + stripTypeScriptTypes(source);
await writeFile(`${portable}/scripts/spec100.cjs`, runtime);
await writeFile('plugins/spec100/runtime/spec100.cjs', runtime);
const setup = (await readFile(`${portable}/SKILL.md`, 'utf8')).replace(/\r\n/g, '\n');
await writeFile(`${templates}/setup.md`, setup);
await cp(templates, 'plugins/spec100/templates', { recursive: true });
await writeFile('plugins/spec100/skills/setup/SKILL.md', setup
  .replace('name: spec100-setup\n', 'name: setup\n')
  .replace('Resolve the bundled runtime at `scripts/spec100.cjs` relative to this skill directory.', 'Resolve the bundled runtime at `${CLAUDE_PLUGIN_ROOT}/runtime/spec100.cjs`.')
  .replace('Select the active tool:', 'For this Claude plugin, select `claude` unless another integration was requested. Available tools:'));
